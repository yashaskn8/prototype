"""Servy V6: guarded research continuation FROM the already-verified V5 checkpoint.

The DEFAULT behavior is a read-only training plan; it does not load GPU weights,
write private data, train, or authorize any use of employer documents.
Actual training requires a separate, genuine organizational permission record
scoped to the dataset and execution environment. This tool cannot grant it.

Selected train rows MUST be the exact V5 provisional subset, never all 353.
The prior 42-question dev split is reused and NOT an independent holdout.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import random
from importlib.metadata import version
from pathlib import Path

from servy_v4_mentor_experiment import (
    audited_inputs, check_storage, demand, provisional_pairs,
)
from servy_v5_training_preflight import admit, read_jsonl, sha256
from servy_checkpoint_audit import evaluate_one
from servy_checkpoint_backup import backup_checkpoint
from servy_accuracy_diagnostics import (
    compare_frozen_pool, sha256_file, simulate_pool_sweep, write_jsonl_exclusive,
)

V5_WEIGHTS_SHA256 = "b1cf23ba0806f0057d73a5ab93fde88d634fc278f71b27f3a2a915afd8f8bcda"


def verify_v5_checkpoint(model_dir):
    """Refuse unrecognized/incomplete V5 checkpoints before training."""
    path = Path(model_dir).expanduser().resolve()
    if not path.is_dir():
        raise ValueError("V5_CHECKPOINT_DIRECTORY_MISSING")
    for required in ("model.safetensors", "config.json"):
        if not (path / required).is_file():
            raise ValueError("V5_CHECKPOINT_FILE_MISSING:" + required)
    actual = sha256(path / "model.safetensors")
    if actual != V5_WEIGHTS_SHA256:
        raise ValueError("V5_CHECKPOINT_WEIGHTS_SHA256_MISMATCH")
    return {"weights_sha256": actual, "model_path": str(path)}


def training_plan(*, split_dir, corpus, families, candidates,
                  candidate_train, manifest, v5_model, out_dir):
    """Compute reproducible metadata only; no output writes."""
    verified = admit(
        split_dir=split_dir, corpus=corpus, families=families,
        candidates=candidates, candidate_train=candidate_train,
        manifest=manifest,
    )
    if verified["status"] != "READY_FOR_EXPLORATORY_FINE_TUNING":
        raise ValueError("RESEARCH_DATA_PREFLIGHT_NOT_READY")
    v5 = verify_v5_checkpoint(v5_model)
    check_storage(out_dir)
    output = Path(out_dir).expanduser().resolve()
    checkpoint = Path(v5_model).expanduser().resolve()
    if output == checkpoint or checkpoint in output.parents or output in checkpoint.parents:
        raise ValueError("OUTPUT_MUST_NOT_OVERLAP_V5_CHECKPOINT")
    if output == Path(candidate_train).resolve() or Path(candidate_train).resolve() in output.parents:
        raise ValueError("OUTPUT_MUST_NOT_OVERLAP_TRAINING_INPUT")
    return {
        "status": "V6_PLAN_READY_TRAINING_NOT_AUTHORIZED",
        "base_checkpoint": v5,
        "selected_train_sha256": verified["candidate_train_sha256"],
        "original_train_sha256": verified["original_train_sha256"],
        "train_queries": verified["train_queries"],
        "positive_pairs": verified["positive_pairs"],
        "negative_pairs": verified["negative_pairs"],
        "dev_queries": verified["dev_queries"],
        "quarantined_negative_references": verified["quarantined_negative_references"],
        "output_location": str(output),
        "starts_from_v5_weights": True,
        "uses_selected_subset_only": True,
        "expert_labels_approved": False,
        "independent_holdout_verified": False,
        "production_promotion_allowed": False,
        "external_training_authorized": False,
        "training_performed": False,
    }


def check_permission(path, *, selected_sha256, environment):
    """Check explicit permission record; cannot independently prove signer authenticity.

    This is intentionally NOT autogenerated from technical-review artifacts.
    A missing/pending record always prevents executing the training pathway.
    """
    if path is None:
        raise ValueError("ORGANIZATIONAL_PERMISSION_RECORD_REQUIRED")
    record_path = Path(path).expanduser().resolve()
    if not record_path.is_file():
        raise ValueError("ORGANIZATIONAL_PERMISSION_RECORD_NOT_FOUND")
    record = json.loads(record_path.read_text(encoding="utf-8"))
    if not isinstance(record, dict):
        raise ValueError("INVALID_ORGANIZATIONAL_PERMISSION_RECORD")
    if record.get("status") != "APPROVED_FOR_RESEARCH_TRAINING":
        raise ValueError("ORGANIZATIONAL_PERMISSION_NOT_APPROVED")
    if not all(isinstance(record.get(key), str) and record[key].strip()
               for key in ("approved_by", "approval_reference")):
        raise ValueError("REVIEWER_AND_APPROVAL_REFERENCE_REQUIRED")
    if record.get("selected_train_sha256") != selected_sha256:
        raise ValueError("PERMISSION_DATASET_FINGERPRINT_MISMATCH")
    if record.get("environment") != environment:
        raise ValueError("PERMISSION_ENVIRONMENT_MISMATCH")
    if environment == "google_colab" and record.get("external_processor_approved") is not True:
        raise ValueError("GOOGLE_COLAB_EXTERNAL_PROCESSOR_NOT_APPROVED")
    return {
        "permission_record_sha256": sha256(record_path),
        "permission_reference": record["approval_reference"],
        "environment": environment,
    }


def train(args, plan, permission):
    """GPU-only bounded research run. Always produces a separate V6 checkpoint."""
    if args.epochs not in (1, 2) or not (1 <= args.batch_size <= 2) or not (
        math.isfinite(args.learning_rate) and 0 < args.learning_rate <= 1e-6
    ):
        raise ValueError("V6_RESEARCH_TRAINING_BOUNDS_EXCEEDED")
    if version("sentence-transformers") != "5.1.0":
        raise ValueError("REQUIRE_SENTENCE_TRANSFORMERS_5_1_0")

    os.environ.setdefault("USE_TF", "0")
    os.environ.setdefault("TRANSFORMERS_NO_TF", "1")
    import numpy as np
    import torch
    from datasets import Dataset
    from sentence_transformers import CrossEncoder
    from sentence_transformers.cross_encoder import (
        CrossEncoderTrainer, CrossEncoderTrainingArguments,
    )
    from sentence_transformers.cross_encoder.losses import BinaryCrossEntropyLoss

    if not torch.cuda.is_available():
        raise ValueError("CUDA_REQUIRED_FOR_V6_FINETUNING")
    # Existing audited_input uses EXACT signed split, corpus, proposed-family
    # isolation and a frozen candidate set; it does not authorize human labels.
    data = audited_inputs(args.split_dir, args.corpus,
                          args.families, args.candidates)
    selected = read_jsonl(args.candidate_train)
    by_chunk = {
        str(row["chunk_id"]): row for row in read_jsonl(args.corpus)
    }
    pairs = provisional_pairs(selected, by_chunk)
    if (len(selected) != plan["train_queries"] or
        sum(x["label"] == 1.0 for x in pairs) != plan["positive_pairs"] or
        sum(x["label"] == 0.0 for x in pairs) != plan["negative_pairs"]):
        raise ValueError("V6_SELECTED_TRAINING_PAIRS_MISMATCH")
    random.seed(42)
    np.random.seed(42)
    torch.manual_seed(42)
    torch.cuda.manual_seed_all(42)

    # Nothing can overwrite V5: its weights are read only and output must
    # not exist, be nested in V5, or overlap an input directory.
    out = Path(args.out_dir).expanduser().resolve()
    check_storage(out)
    out.mkdir(mode=0o700)
    input_hashes = {
        "v5_weights": sha256_file(Path(args.v5_model) / "model.safetensors"),
        "train_subset": sha256_file(args.candidate_train),
        "frozen_candidates": sha256_file(args.candidates),
        "corpus": sha256_file(args.corpus),
        "dev_split": sha256_file(Path(args.split_dir) / "dev_unapproved_candidate.jsonl"),
    }
    if input_hashes["v5_weights"] != V5_WEIGHTS_SHA256:
        raise ValueError("V5_WEIGHTS_CHANGED_BEFORE_TRAINING")
    if input_hashes["train_subset"] != plan["selected_train_sha256"]:
        raise ValueError("V6_TRAIN_SUBSET_CHANGED_AFTER_PREFLIGHT")
    summary = {
        **plan,
        "input_sha256": input_hashes,
        "evaluation_protocol": {
            "candidate_source": "frozen_input",
            "pool_size": 5,
            "top_k": 10,
            "checkpoint_selection": "minimum_development_bce_loss",
            "no_independent_test": True,
        },
        "training_config": {
            "epochs": args.epochs,
            "batch_size": args.batch_size,
            "learning_rate": args.learning_rate,
            "seed": 42,
            "objective": "BinaryCrossEntropyLoss",
        },
        "status": "V6_EXPLORATORY_IN_PROGRESS",
        "permission": permission,
        "data_status": "PROVISIONAL_TECHNICALLY_REVIEWED_NO_HUMAN_LABEL_SIGNOFF",
        "training_performed": False,
    }
    (out / "experiment_manifest.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )

    model = CrossEncoder(
        str(Path(args.v5_model).expanduser().resolve()),
        max_length=256, device="cuda", local_files_only=True,
    )

    def score(checkpoint):
        def scorer(pairs_to_score):
            raw = checkpoint.predict(
                pairs_to_score, activation_fn=torch.nn.Identity(),
                show_progress_bar=False,
            )
            return np.asarray(raw).ravel().tolist()
        return scorer

    before = evaluate_one(
        data["cases"], data["chunks"], data["frozen"],
        score(model), pool_size=5,
    )
    (out / "v5_dev_metrics.json").write_text(
        json.dumps(before["metrics"], indent=2) + "\n", encoding="utf-8"
    )
    # Per-query records remain in the approved private experiment directory.
    # Without these records, identical aggregate metrics conceal regressions.
    write_jsonl_exclusive(out / "v5_dev_per_query.jsonl", before["queries"])
    use_bf16 = bool(torch.cuda.is_bf16_supported())
    training_args = CrossEncoderTrainingArguments(
        output_dir=str(out / "trainer"),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.batch_size,
        learning_rate=args.learning_rate,
        warmup_ratio=0.05,
        eval_strategy="epoch", save_strategy="epoch",
        load_best_model_at_end=True, metric_for_best_model="eval_loss",
        greater_is_better=False, save_total_limit=2,
        logging_steps=1, seed=42, data_seed=42,
        bf16=use_bf16, fp16=not use_bf16,
        dataloader_num_workers=0, report_to="none", push_to_hub=False,
    )
    trainer = CrossEncoderTrainer(
        model=model, args=training_args,
        train_dataset=Dataset.from_list(pairs),
        eval_dataset=Dataset.from_list(data["dev_pairs"]),
        loss=BinaryCrossEntropyLoss(model),
    )
    trainer.train()
    if trainer.state.best_model_checkpoint is None:
        raise ValueError("V6_NO_SELECTED_CHECKPOINT")
    if trainer.state.best_metric is None or not math.isfinite(
        float(trainer.state.best_metric)
    ):
        raise ValueError("V6_BEST_DEV_LOSS_INVALID")
    # Trainer loads best model at the end. Save separately; verified backup
    # must not overwrite any existing V5 file.
    working_best = out / "selected_model"
    trainer.model.save_pretrained(str(working_best))
    backup_checkpoint(working_best, out / "best_model")
    trained = CrossEncoder(
        str(out / "best_model"), max_length=256,
        device="cuda", local_files_only=True,
    )
    after = evaluate_one(
        data["cases"], data["chunks"], data["frozen"],
        score(trained), pool_size=5,
    )
    final_hashes = {
        "v5_weights": sha256_file(Path(args.v5_model) / "model.safetensors"),
        "train_subset": sha256_file(args.candidate_train),
        "frozen_candidates": sha256_file(args.candidates),
        "corpus": sha256_file(args.corpus),
        "dev_split": sha256_file(Path(args.split_dir) / "dev_unapproved_candidate.jsonl"),
    }
    if final_hashes != input_hashes:
        raise ValueError("V6_INPUT_DRIFT_DETECTED_NO_VALID_COMPARISON")
    audit = compare_frozen_pool(before, after, data["frozen"], pool_size=5)
    write_jsonl_exclusive(out / "v6_dev_per_query.jsonl", after["queries"])
    write_jsonl_exclusive(out / "v5_v6_paired_per_query.jsonl", audit["per_query"])
    (out / "v5_v6_accuracy_diagnostics.json").write_text(
        json.dumps(audit["summary"], indent=2) + "\n", encoding="utf-8"
    )
    # Counterfactual analysis reuses logits already scored on frozen candidates.
    # It does not change the serving pool, select checkpoints or promote a model.
    pool_audit = {
        "v5": simulate_pool_sweep(before, data["frozen"]),
        "v6": simulate_pool_sweep(after, data["frozen"]),
        "status": "REUSED_DEV_COUNTERFACTUAL_NOT_PRODUCTION_CONFIG",
    }
    for checkpoint, report in (("v5", before), ("v6", after)):
        pool_five = pool_audit[checkpoint][0]
        for metric in ("hit_at_1", "hit_at_5", "hit_at_10", "mrr_at_10"):
            if pool_five[metric] != report["metrics"][metric]:
                raise ValueError("V6_POOL_SWEEP_METRIC_REPLAY_MISMATCH:" + checkpoint + ":" + metric)
    (out / "v5_v6_pool_sweep.json").write_text(
        json.dumps(pool_audit, indent=2) + "\n", encoding="utf-8"
    )
    summary.update({
        "status": "V6_EXPLORATORY_COMPLETED_NOT_PROMOTED",
        "training_performed": True,
        "best_dev_loss": float(trainer.state.best_metric),
        "v6_weights_sha256": sha256(out / "best_model" / "model.safetensors"),
        "v5_dev_metrics": before["metrics"],
        "v6_dev_metrics": after["metrics"],
        "paired_diagnostics": audit["summary"],
        "dev_comparison_is_reused_diagnostic_only": True,
        "independent_holdout_verified": False,
        "production_promotion_allowed": False,
    })
    (out / "experiment_manifest.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ("split-dir", "corpus", "families", "candidates",
                   "candidate-train", "manifest", "v5-model", "out-dir"):
        parser.add_argument("--" + option, required=True)
    parser.add_argument("--train", action="store_true",
                        help="Execute only with genuine scoped organizational authorization")
    parser.add_argument("--authorization-file")
    parser.add_argument("--execution-environment", choices=("local_secure", "google_colab"),
                        default="local_secure")
    parser.add_argument("--epochs", type=int, default=1)
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--learning-rate", type=float, default=3e-7)
    args = parser.parse_args()
    plan = training_plan(**{
        key: getattr(args, key) for key in
        ("split_dir", "corpus", "families", "candidates", "candidate_train",
         "manifest", "v5_model", "out_dir")
    })
    if args.train:
        permission = check_permission(
            args.authorization_file, selected_sha256=plan["selected_train_sha256"],
            environment=args.execution_environment,
        )
        result = train(args, plan, permission)
    else:
        result = plan
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
